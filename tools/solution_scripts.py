#!/usr/bin/env python3
"""Write the scripts of a practice set's solution videos as one Markdown file.

    python3 tools/solution_scripts.py exercises/u00-l01    # -> video-scripts/u00-l01-solutions.md

Solution videos are generated from exercises.json (docs/exercises.md); this file shows them in
the same format as the lesson scripts (docs/video-scripts.md) so they can be read and reviewed
together: objective, what the solution covers, the transcript, what the screen shows, and the
real length from timeline.json.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LEVELS = {1: "Warm-up", 2: "Tricky", 3: "Challenging", 4: "Boss level"}
KIND = {"num": "find the value", "expr": "expand the expression", "name": "name the property",
        "multi": "select all that apply", "match": "matching"}


def clean(expr):
    """⟨…⟩ marks and [[a | b]] fractions of exercises.json, as plain text."""
    expr = re.sub(r"\[\[(.+?) \| (.+?)\]\]", r"(\1)/(\2)", expr)
    return expr.replace("⟨", "").replace("⟩", "")


def answer(ex):
    """The right answer of any kind of exercise, as Markdown."""
    if ex.get("a"):
        return f"`{clean(ex['a'])}`"
    if ex.get("options"):
        return " and ".join(f"`{o['t']}`" for o in ex["options"] if o.get("ok"))
    if ex.get("pairs"):
        return "; ".join(f"`{p['l']}` ↔ {p['r']}" for p in ex["pairs"])
    return f"`{clean(ex['lines'][-1])}`" if ex.get("lines") else "—"


def mmss(s):
    s = round(s)
    return f"{s // 60}:{s % 60:02d}"


def main():
    folder = ROOT / sys.argv[1]
    data = json.loads((folder / "exercises.json").read_text(encoding="utf-8"))
    set_id = folder.name                                   # u00-l01: one set per topic
    number = f"{int(set_id[1:3])}.{int(set_id[5:7])}"
    if "-s" in set_id:
        number += "." + set_id.split("-s")[1]
    out = [f"# Solution videos · Practice set {number} — {data.get('title', '')}", "",
           "Generated by `tools/solution_scripts.py` from the produced `script.json` of each video; "
           "the source of truth is "
           f"[`exercises/{set_id}/exercises.json`](../exercises/{set_id}/exercises.json). "
           "Do not edit by hand. Lengths are the real narration (`timeline.json`).", ""]
    total = 0.0
    rows = []
    body = []
    for ex in data["exercises"]:
        vid = f"{set_id}-{ex['id']}"
        vdir = ROOT / "videos" / vid
        if not (vdir / "script.json").exists():
            continue
        script = json.loads((vdir / "script.json").read_text(encoding="utf-8"))
        length = None
        if (vdir / "timeline.json").exists():
            length = json.loads((vdir / "timeline.json").read_text(encoding="utf-8"))["duration"]
            total += length
        n = int(ex["id"][2:])
        kind = KIND.get(ex.get("kind", "num"), ex.get("kind", ""))
        level = LEVELS.get(ex.get("level"), "")
        q = clean(ex.get("q") or ex.get("prompt", ""))
        rows.append(f"| {n} | `{q}` | {level} | {kind} | {mmss(length) if length else '—'} |")
        body += [f"## Exercise {n} · `{q}`",
                 f"- **Video:** `{vid}`",
                 "- **Status:** produced",
                 f"- **Length:** {mmss(length) if length else '—'} (real narration)",
                 "",
                 f"**Objective.** Show, step by step, why the answer to `{q}` is "
                 f"{answer(ex)}, "
                 f"and name the mistakes that lead to the wrong answers. Level {ex.get('level')} "
                 f"({level}), {kind}.",
                 ""]
        steps = [clean(line) for line in ex.get("lines") or ex.get("show") or []]
        if steps:
            body += ["**Topics.**", "- Solution: " + " → ".join(f"`{s}`" for s in steps)]
        wrong = [w.get("why") for w in ex.get("wrong", []) if w.get("why")]
        wrong += [o["why"] for o in ex.get("options", []) if not o.get("ok") and o.get("why")]
        if wrong:
            body += ["- Known mistakes: " + " · ".join(wrong)]
        body.append("")
        for scene in script["scenes"]:
            body.append(f"#### {scene['id'].upper()} · {scene.get('title', '')}")
            for b in scene["blocks"]:
                if b.get("display"):
                    body.append(f"*Screen:* `{b['display']}`" + (f" ({b['cue']})" if b.get("cue") else ""))
                body.append(f"> {b['text']}")
                if b.get("pause_after_s"):
                    body.append(f"[THINK {b['pause_after_s']}s] *Screen:* the problem stays.")
        body.append("")
    out += ["| # | Exercise | Level | Kind | Length |", "|---|---|---|---|---|", *rows,
            f"| | **{len(rows)} videos** | | | **{mmss(total)}** |", "", *body]
    dest = ROOT / "video-scripts" / f"{set_id}-solutions.md"
    dest.write_text("\n".join(out), encoding="utf-8")
    print(f"{dest.relative_to(ROOT)}: {len(rows)} videos, {mmss(total)}")


if __name__ == "__main__":
    main()
